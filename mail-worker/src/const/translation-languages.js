export function normalizeLanguageCode(code) {
 if(typeof code !== 'string' || !/^[a-zA-Z]{2,3}(?:-[a-zA-Z0-9]{2,8}){0,2}$/.test(code.trim())) return null;
 const known=translationLanguage(code.trim());if(known)return known.id;
 try { const canonical=Intl.getCanonicalLocales(code.trim())[0]; return translationLanguage(canonical)?.id || canonical; } catch { return null; }
}
